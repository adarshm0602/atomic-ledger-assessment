-- Apply once with the project owner's SQL editor before deploying.
-- ledger is a private schema, not exposed in the Supabase Data API.
CREATE SCHEMA IF NOT EXISTS ledger;
CREATE TABLE IF NOT EXISTS ledger.accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK(length(trim(name)) BETWEEN 1 AND 100),
    balance_cents BIGINT NOT NULL DEFAULT 0 CHECK(balance_cents BETWEEN 0 AND 99999999999999),
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS ledger.transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_account_id BIGINT NOT NULL REFERENCES ledger.accounts(id),
    destination_account_id BIGINT NOT NULL REFERENCES ledger.accounts(id),
    amount_cents BIGINT NOT NULL CHECK(amount_cents BETWEEN 1 AND 99999999999999),
    reference_id TEXT NOT NULL CHECK(length(trim(reference_id)) BETWEEN 1 AND 128),
    created_at TEXT NOT NULL,
    CHECK(source_account_id != destination_account_id),
    UNIQUE(source_account_id, reference_id)
);
CREATE TABLE IF NOT EXISTS ledger.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES ledger.accounts(id),
    type TEXT NOT NULL CHECK(type IN ('credit', 'debit')),
    amount_cents BIGINT NOT NULL CHECK(amount_cents BETWEEN 1 AND 99999999999999),
    balance_after_cents BIGINT NOT NULL CHECK(balance_after_cents BETWEEN 0 AND 99999999999999),
    reference_id TEXT NOT NULL CHECK(length(trim(reference_id)) BETWEEN 1 AND 128),
    transfer_id BIGINT REFERENCES ledger.transfers(id),
    created_at TEXT NOT NULL,
    UNIQUE(account_id, reference_id)
);
CREATE INDEX IF NOT EXISTS transactions_account_id_id ON ledger.transactions(account_id, id DESC);
CREATE INDEX IF NOT EXISTS transactions_transfer_id ON ledger.transactions(transfer_id);
CREATE INDEX IF NOT EXISTS transfers_destination_account_id ON ledger.transfers(destination_account_id);
ALTER TABLE ledger.accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE ledger.transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE ledger.transfers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON SCHEMA ledger FROM PUBLIC, anon, authenticated;
-- A dedicated server-only LOGIN role is provisioned separately, with a random
-- password stored only in the hosting environment. No credential belongs here.
